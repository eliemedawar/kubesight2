"""node_modules kept between builds, one archive per lockfile.

The package managers' download caches make "Fetching packages" fast and do
nothing for yarn's "[4/4] Building fresh packages" - every dependency's install
script runs again into an empty node_modules. These tests cover the one thing
that fixes it: an install stage restores the node_modules its lockfile produced
last time, and saves it when there was none.

Most of these RUN the generated shell against a throwaway project with a fake
``yarn``/``npm`` on PATH, because the contract is behaviour (restored, saved,
not saved on failure, exit code kept), not text.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

from api.services.ci import cache_layout
from api.services.ci.runners import kubernetes as k8s
from api.services.ci.runners.base import StageExecution

SH = shutil.which("sh")
needs_sh = pytest.mark.skipif(not SH or not shutil.which("tar"), reason="needs sh and tar")


# -- which stages ---------------------------------------------------------------


@pytest.mark.parametrize(
    "command",
    [
        "yarn install",
        "yarn",
        "yarn --frozen-lockfile",
        "corepack yarn install --frozen-lockfile",
        "npm ci",
        "npm install --legacy-peer-deps",
        "npm i",
        "pnpm install",
        "corepack pnpm i --frozen-lockfile",
        "if [ -f yarn.lock ]; then corepack yarn install --frozen-lockfile; "
        "elif [ -f package-lock.json ]; then npm ci; else npm install; fi",
        "cd web && yarn",
    ],
)
def test_an_install_command_is_recognised(command):
    assert cache_layout.runs_node_install([command])


@pytest.mark.parametrize(
    "command",
    [
        "yarn build",
        "npm run build",
        "npm test",
        "pnpm run lint",
        "./gradlew build",
        "echo yarnish",
        "cat yarn.lock",
    ],
)
def test_other_commands_are_not_install_stages(command):
    assert not cache_layout.runs_node_install([command])


def _execution(commands, **extra) -> StageExecution:
    values = dict(
        build_id=1,
        build_number=1,
        stage_id=2,
        service_slug="acquiring-ui",
        stage_name="Install Dependencies",
        stage_type="command",
        image="node:16-bullseye",
        working_directory=None,
        commands=commands,
        env={},
        position=1,
    )
    values.update(extra)
    return StageExecution(**values)


def test_the_runner_wraps_only_install_stages_with_the_cache_on(monkeypatch):
    monkeypatch.setenv("CI_CACHE_CLAIM_NAME", "ci-cache")
    monkeypatch.delenv("CI_CACHE_NODE_MODULES", raising=False)
    assert "ks_nm_prepare" in k8s._command_stage_script(_execution(["yarn install"]))
    assert "ks_nm_prepare" not in k8s._command_stage_script(_execution(["yarn build"]))

    monkeypatch.setenv("CI_CACHE_NODE_MODULES", "0")
    assert "ks_nm_prepare" not in k8s._command_stage_script(_execution(["yarn install"]))


def test_a_cache_off_build_carries_none_of_it(monkeypatch):
    monkeypatch.delenv("CI_CACHE_CLAIM_NAME", raising=False)
    monkeypatch.delenv("CI_CACHE_STORAGE_CLASS", raising=False)
    monkeypatch.setattr(k8s, "cache_enabled", lambda: False)
    assert "ks_nm_prepare" not in k8s._command_stage_script(_execution(["yarn install"]))


def test_the_script_is_ascii():
    assert cache_layout.node_modules_wrap("yarn install", image="node:16").isascii()


# -- running it -----------------------------------------------------------------


@pytest.fixture
def project(tmp_path):
    """A checkout, a cache directory and a fake yarn + npm that count their calls
    and "build" a node_modules the slow way."""
    src = tmp_path / "src"
    src.mkdir()
    (src / "package.json").write_text('{"name": "app"}\n')
    (src / "yarn.lock").write_text("left-pad@1.0.0\n")
    cache = tmp_path / "cache"
    cache.mkdir()
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    calls = tmp_path / "calls"
    for tool in ("yarn", "npm"):
        fake = bin_dir / tool
        fake.write_text(
            "#!/bin/sh\n"
            f'echo "{tool} $*" >> "{calls.as_posix()}"\n'
            'if [ "${1:-}" = ci ]; then rm -rf node_modules; fi\n'
            "if [ ! -f node_modules/left-pad/built ]; then\n"
            "  mkdir -p node_modules/left-pad node_modules/.bin\n"
            "  echo compiled > node_modules/left-pad/built\n"
            f'  echo built >> "{calls.as_posix()}"\n'
            "fi\n"
        )
        fake.chmod(0o755)
    return {"src": src, "cache": cache, "bin": bin_dir, "calls": calls}


def _run(project, commands, env=None):
    script = "set -eu\n" + cache_layout.node_modules_wrap(commands, image="node:16") + "\n"
    full_env = dict(os.environ)
    full_env["PATH"] = project["bin"].as_posix() + os.pathsep + full_env.get("PATH", "")
    full_env["KUBESIGHT_CACHE_DIR"] = project["cache"].as_posix()
    full_env.update(env or {})
    return subprocess.run(
        [SH, "-c", script],
        cwd=project["src"],
        env=full_env,
        capture_output=True,
        text=True,
        timeout=60,
    )


def _archives(project):
    return sorted((project["cache"] / cache_layout.NODE_MODULES_SUBDIR).glob("*.tar"))


def _built_count(project):
    return project["calls"].read_text().splitlines().count("built")


def _fresh_checkout(project):
    shutil.rmtree(project["src"] / "node_modules", ignore_errors=True)


@needs_sh
def test_the_first_install_is_saved_and_the_second_is_restored(project):
    first = _run(project, "yarn install")
    assert first.returncode == 0, first.stderr
    assert "runs cold and is saved after" in first.stdout
    assert "saved" in first.stdout
    assert len(_archives(project)) == 1
    assert _built_count(project) == 1

    _fresh_checkout(project)
    second = _run(project, "yarn install")
    assert second.returncode == 0, second.stderr
    assert "restored" in second.stdout
    # The install still ran - root lifecycle scripts still happen - but found the
    # tree already built.
    assert _built_count(project) == 1
    assert (project["src"] / "node_modules/left-pad/built").read_text().strip() == "compiled"


@needs_sh
def test_a_changed_lockfile_is_a_new_key(project):
    _run(project, "yarn install")
    _fresh_checkout(project)
    (project["src"] / "yarn.lock").write_text("left-pad@1.1.0\n")
    result = _run(project, "yarn install")
    assert "nothing saved for this lockfile yet" in result.stdout
    assert _built_count(project) == 2
    assert len(_archives(project)) == 2


@needs_sh
def test_old_keys_are_pruned(project):
    for version in range(cache_layout.NODE_MODULES_KEEP + 2):
        _fresh_checkout(project)
        (project["src"] / "yarn.lock").write_text(f"left-pad@1.{version}.0\n")
        assert _run(project, "yarn install").returncode == 0
    assert len(_archives(project)) == cache_layout.NODE_MODULES_KEEP


@needs_sh
def test_a_failed_install_is_not_saved_and_still_fails(project):
    result = _run(project, "yarn install\nfalse")
    assert result.returncode != 0
    assert _archives(project) == []


@needs_sh
def test_a_non_zero_status_that_set_e_lets_through_is_kept(project):
    # `[ ... ] && ...` does not trip set -e, but its status was the stage's
    # status before the wrap, and must stay so.
    result = _run(project, "yarn install\n[ -f nope ] && echo never")
    assert result.returncode == 1
    assert _archives(project) == []


@needs_sh
def test_npm_ci_after_a_restore_keeps_the_tree(project):
    (project["src"] / "yarn.lock").unlink()
    (project["src"] / "package-lock.json").write_text("{}\n")
    assert _run(project, "npm ci").returncode == 0
    _fresh_checkout(project)
    result = _run(project, "npm ci")
    assert result.returncode == 0, result.stderr
    assert "npm ci -> npm install --no-save" in result.stdout
    assert "npm install --no-save" in project["calls"].read_text()
    assert _built_count(project) == 1


@needs_sh
def test_a_stage_can_switch_it_off(project):
    result = _run(project, "yarn install", env={"KUBESIGHT_NODE_MODULES_CACHE": "0"})
    assert result.returncode == 0
    assert "off for this stage" in result.stdout
    assert _archives(project) == []


@needs_sh
def test_an_existing_node_modules_is_left_alone_and_not_saved(project):
    (project["src"] / "node_modules").mkdir()
    result = _run(project, "yarn install")
    assert result.returncode == 0
    assert "already here" in result.stdout
    assert _archives(project) == []


@needs_sh
def test_no_lockfile_means_a_cold_install(project):
    (project["src"] / "yarn.lock").unlink()
    result = _run(project, "yarn install")
    assert result.returncode == 0
    assert "no lockfile" in result.stdout
    assert _archives(project) == []


@needs_sh
def test_a_corrupt_archive_is_discarded_not_fatal(project):
    _run(project, "yarn install")
    (archive,) = _archives(project)
    archive.write_bytes(b"not a tar")
    _fresh_checkout(project)
    result = _run(project, "yarn install")
    assert result.returncode == 0
    assert "could not be read" in result.stderr
    assert _built_count(project) == 2


@needs_sh
def test_cache_off_is_a_plain_install(project):
    result = _run(project, "yarn install", env={"KUBESIGHT_CACHE_DIR": ""})
    assert result.returncode == 0
    assert "node_modules cache" not in result.stdout
    assert _archives(project) == []


# -- the Linux and Mac agents -------------------------------------------------------
#
# The server wraps an agent task's install commands with the same text, so the
# agent only has to say where the archives go. A Mac (or Linux without docker)
# runs in host mode with no KUBESIGHT_CACHE_DIR at all.

import importlib.util

from api.services.ci import agents as agents_service

AGENT_PATH = Path(__file__).resolve().parents[2] / "agent" / "kubesight-agent.py"


@pytest.fixture(scope="module")
def agent():
    spec = importlib.util.spec_from_file_location("kubesight_agent_nm", AGENT_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_server_wraps_an_agent_install_task(monkeypatch):
    monkeypatch.delenv("CI_CACHE_NODE_MODULES", raising=False)
    payload = {"commands": ["yarn install"]}
    agents_service._add_node_modules_cache(payload, _execution(["yarn install"], service_slug="Acquiring UI"))
    assert payload["cacheSlug"] == "acquiring-ui"
    assert len(payload["commands"]) == 1
    assert "ks_nm_prepare" in payload["commands"][0]
    assert "yarn install" in payload["commands"][0]


def test_the_server_leaves_other_agent_tasks_alone(monkeypatch):
    monkeypatch.delenv("CI_CACHE_NODE_MODULES", raising=False)
    payload = {"commands": ["yarn build"]}
    agents_service._add_node_modules_cache(payload, _execution(["yarn build"]))
    assert payload["commands"] == ["yarn build"]

    monkeypatch.setenv("CI_CACHE_NODE_MODULES", "off")
    payload = {"commands": ["yarn install"]}
    agents_service._add_node_modules_cache(payload, _execution(["yarn install"]))
    assert payload["commands"] == ["yarn install"]


def test_the_agent_gives_each_service_its_own_archive_directory(agent):
    assert agent.node_modules_dir("/data/.cache", {"cacheSlug": "acquiring-ui"}) == (
        "/data/.cache/node-modules/acquiring-ui"
    )
    # It becomes a path on the agent's machine, so it is checked again there.
    for bad in ("", "../etc", "a/b", "Upper", "-x", None):
        assert agent.node_modules_dir("/data/.cache", {"cacheSlug": bad}) == ""


def test_a_container_stage_on_the_agent_gets_the_directory(agent):
    task = {"taskId": 1, "buildId": 1, "image": "node:16", "env": {}, "cacheSlug": "acquiring-ui"}
    argv = agent.container_command("docker", task, "/w", "/data/.cache", "yarn", uid_gid="1:1")
    assert "KUBESIGHT_NODE_MODULES_DIR=/cache/node-modules/acquiring-ui" in argv

    task["env"] = {"KUBESIGHT_NODE_MODULES_DIR": "/elsewhere"}
    argv = agent.container_command("docker", task, "/w", "/data/.cache", "yarn", uid_gid="1:1")
    assert "KUBESIGHT_NODE_MODULES_DIR=/cache/node-modules/acquiring-ui" not in argv


@needs_sh
def test_host_mode_keeps_node_modules_without_a_cache_dir(project, tmp_path):
    """What a Mac agent does: no container, no KUBESIGHT_CACHE_DIR, just the
    directory the agent named - and `sh -e`, which is how the agent runs it."""
    archives = tmp_path / "agent-cache" / "node-modules" / "acquiring-ui"
    env = {"KUBESIGHT_CACHE_DIR": "", "KUBESIGHT_NODE_MODULES_DIR": archives.as_posix()}
    assert _run(project, "yarn install", env=env).returncode == 0
    assert len(list(archives.glob("*.tar"))) == 1
    _fresh_checkout(project)
    second = _run(project, "yarn install", env=env)
    assert "restored" in second.stdout
    assert _built_count(project) == 1
